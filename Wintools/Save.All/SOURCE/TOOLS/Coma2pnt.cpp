#include <string.h>

//------------------------------------------------------------------------------
//	스트링에 있는 , 를 . 으로 바꿔준다.
//------------------------------------------------------------------------------

void CommaToPoint(char *string)
{
	int i;

	for(i = 0; i < (int)strlen(string); i++) {
		if(string[i] == ',')	string[i] = '.';
	}
}



