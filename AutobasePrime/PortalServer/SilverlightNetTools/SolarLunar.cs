        static int[] m_limit = { 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31 };

        public static int ConvertSolarToLunar(DATE_SOLAR_LUNAR date)
        {
            int lyear;
            int lmon;
            int lday;
            int leap;

            int retn = ConvertSolarToLunar(date.syear, date.smon, date.sday, out lyear, out lmon, out lday, out leap);

            date.lyear = lyear;
            date.lmon = lmon;
            date.lday = lday;
            date.leap = leap;

            return retn;
        }

        public static int ConvertSolarToLunar(int syear, int smon, int sday, out int lyear, out int lmon, out int lday, out int leapyes)
        {
            lyear = 2002;
            lmon = 1;
            lday = 1;
            leapyes = 0;

            if (syear < 1881) return 0;
            if (syear > YEAR_LIMIT) return 0;
            if (smon < 1) return 0;
            if (smon > 12) return 0;
            if (sday < 1) return 0;
            if (sday > 31) return 0;

            if (syear == 1881)
            {
                if (smon == 1 && sday < 30) return 0;
            }

            int shap = 0;
            int lhap = 0;
            int year, mon;

            for (year = 1881; year < syear; year++)
            {
                if ((year % 400) == 0) shap += 366;
                else if ((year % 100) == 0) shap += 365;
                else if ((year % 4) == 0) shap += 366;
                else shap += 365;
            }



            for (mon = 1; mon < 12 && mon < smon; mon++)
            {
                if (mon == 2)
                {
                    if ((syear % 400) == 0) shap += 29;
                    else if ((syear % 100) == 0) shap += 28;
                    else if ((syear % 4) == 0) shap += 29;
                    else shap += 28;
                }
                else
                {
                    shap += m_limit[mon - 1];
                }
            }

            shap += sday;
            shap -= 29;

            int array_size_year = YEAR_LIMIT - 1880;

            for (year = 0; year < array_size_year; year++)
            {
                for (mon = 0; mon < 13; mon++)
                {
                    if (kk[year * 13 + mon] == 1 || kk[year * 13 + mon] == 3)
                    {
                        lhap += 29;
                    }
                    else if (kk[year * 13 + mon] == 2 || kk[year * 13 + mon] == 4)
                    {
                        lhap += 30;
                    }
                    else { }

                    if (lhap >= shap)
                    {	// over
                        if (kk[year * 13 + mon] == 1 || kk[year * 13 + mon] == 3)
                        {
                            lhap -= 29;
                        }
                        else if (kk[year * 13 + mon] == 2 || kk[year * 13 + mon] == 4)
                        {
                            lhap -= 30;
                        }
                        else { }
                        goto calc_start;
                    }
                }
            }

        calc_start:
            lyear = year + 1881;

            if (kk[year * 13 + 12] == 0)
            {
                lmon = mon + 1;
            }
            else
            {
                lmon = 0;
                for (int m = 0; m <= mon && m < 13; m++)
                {
                    if (kk[year * 13 + m] > 2)
                    {

                    }
                    else
                    {
                        lmon++;
                    }
                }
            }
            lday = shap - lhap;
            if (kk[year * 13 + mon] > 2)
                leapyes = 1;
            else
                leapyes = 0;

            return 1;
        }

        public static int GetMonthLimitLunar(int lyear, int lmon, int leap_flag)
        {
            if (lyear < 1881) return 30;	// table over
            if (lyear > YEAR_LIMIT) return 30;
            if (lmon < 1) return 30;
            if (lmon > 12) return 30;

            int year_pos = lyear - 1881;
            int value = 2;	// 30일

            if (kk[year_pos * 13 + 12] == 0)
            {	// 윤달이 없다.
                value = kk[year_pos * 13 + (lmon - 1)];
            }
            else
            {
                if (leap_flag == 1 && kk[year_pos * 13 + lmon] > 2)
                {	// 
                    value = kk[year_pos * 13 + lmon];
                }
                else
                {
                    int mon = 0;

                    for (int m = 0; m < 13; m++)
                    {
                        if (kk[year_pos * 13 + m] > 2)
                        {
                        }
                        else
                        {
                            mon++;
                        }

                        if (mon == lmon)
                        {
                            value = kk[year_pos * 13 + m];
                            break;
                        }
                    }
                }
            }

            if (value == 1 || value == 3) return 29;
            else return 30;
        }
